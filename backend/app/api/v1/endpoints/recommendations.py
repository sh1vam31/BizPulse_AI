from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session
from app.api.deps import get_current_active_user, get_db
from app.models.auth import User
from app.models.decision import Recommendation
from app.schemas.decision import (
    ExplainRecommendationResponse,
    GenerateRecommendationsResponse,
    RecommendationDetailResponse,
    RecommendationResponse,
)
from app.services.decision_engine import evaluate_and_generate_recommendations
from app.services.llm_explainer import generate_recommendation_explanation

router = APIRouter()


@router.get("", response_model=List[RecommendationResponse])
def list_recommendations(
    module: Optional[str] = Query(None, description="SupplyChain or Revenue"),
    priority: Optional[str] = Query(None, description="LOW, MEDIUM, HIGH, CRITICAL"),
    status: Optional[str] = Query("PENDING", description="PENDING, APPROVED, REJECTED, EXECUTED"),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    query = db.query(Recommendation).filter(
        Recommendation.organization_id == current_user.organization_id
    )
    if module:
        query = query.filter(Recommendation.module == module)
    if priority:
        query = query.filter(Recommendation.priority == priority)
    if status:
        query = query.filter(Recommendation.status == status)

    recs = query.order_by(Recommendation.created_at.desc()).offset(offset).limit(limit).all()
    return recs


@router.get("/{recommendation_id}", response_model=RecommendationDetailResponse)
def get_recommendation_detail(
    recommendation_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    rec = (
        db.query(Recommendation)
        .filter(
            Recommendation.id == recommendation_id,
            Recommendation.organization_id == current_user.organization_id,
        )
        .first()
    )
    if not rec:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Recommendation {recommendation_id} not found",
        )

    # Determine suggested action type and mock payload
    if rec.recommendation_type == "REPLENISH_INVENTORY":
        action_type = "CREATE_PURCHASE_ORDER"
        payload = {
            "product_id": rec.affected_entity_id,
            "quantity": rec.evidence.get("recommended_replenishment_quantity", 50) if rec.evidence else 50,
            "notes": "Automated replenishment generated by BusinessPulse AI",
        }
    elif rec.recommendation_type == "CHURN_RETENTION":
        action_type = "CREATE_RETENTION_TASK"
        payload = {
            "customer_id": rec.affected_entity_id,
            "campaign": "Executive Retention Outreach & Loyalty Discount",
        }
    elif rec.recommendation_type == "REVIEW_SUPPLIER":
        action_type = "FLAG_SUPPLIER_REVIEW"
        payload = {
            "supplier_id": rec.affected_entity_id,
            "review_reason": "Low on-time delivery rate under SLA",
        }
    else:
        action_type = "GENERAL_INVESTIGATION_TASK"
        payload = {"entity_id": rec.affected_entity_id}

    return RecommendationDetailResponse(
        id=rec.id,
        organization_id=rec.organization_id,
        module=rec.module,
        recommendation_type=rec.recommendation_type,
        title=rec.title,
        description=rec.description,
        affected_entity_type=rec.affected_entity_type,
        affected_entity_id=rec.affected_entity_id,
        evidence=rec.evidence,
        expected_financial_impact=float(rec.expected_financial_impact),
        priority=rec.priority,
        status=rec.status,
        created_at=rec.created_at,
        ai_explanation=rec.description,
        suggested_action_type=action_type,
        action_payload=payload,
    )


@router.post("/generate", response_model=GenerateRecommendationsResponse)
def trigger_recommendation_generation(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    recs, summary = evaluate_and_generate_recommendations(
        db=db, organization_id=current_user.organization_id
    )
    return GenerateRecommendationsResponse(
        total_generated=len(recs),
        recommendations=recs,
        evaluation_summary=summary,
    )


@router.get("/{recommendation_id}/explain", response_model=ExplainRecommendationResponse)
@router.post("/{recommendation_id}/explain", response_model=ExplainRecommendationResponse)
def explain_recommendation(
    recommendation_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    rec = (
        db.query(Recommendation)
        .filter(
            Recommendation.id == recommendation_id,
            Recommendation.organization_id == current_user.organization_id,
        )
        .first()
    )
    if not rec:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Recommendation {recommendation_id} not found",
        )

    evidence = rec.evidence or {}
    explanation, generated_by = generate_recommendation_explanation(
        recommendation_type=rec.recommendation_type,
        title=rec.title,
        evidence=evidence,
        expected_impact=float(rec.expected_financial_impact),
    )

    return ExplainRecommendationResponse(
        recommendation_id=rec.id,
        title=rec.title,
        explanation=explanation,
        grounded_evidence=evidence,
        generated_by=generated_by,
    )
